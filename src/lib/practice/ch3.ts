import { rnd, nz, pick, shuffle, R, frac, poly, polyP, pmul, factor, choice, type Problem } from '../gen';

type Gen = () => Problem;
const ps = (k: number) => (k < 0 ? `(${k})` : String(k));
const lead = (a: number) => (a === 1 ? '' : a === -1 ? '-' : String(a));
const sq = (h: number) => (h === 0 ? 'x^2' : `(x ${h > 0 ? '-' : '+'} ${Math.abs(h)})^2`);
/** القسمة التركيبية: يعيد [خارج القسمة، الباقي] */
function synth(A: number[], k: number): [number[], number] {
  const b: number[] = [];
  A.forEach((a, i) => b.push(i === 0 ? a : a + b[i - 1] * k));
  return [b.slice(0, -1), b[b.length - 1]];
}

